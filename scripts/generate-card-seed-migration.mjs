#!/usr/bin/env node
// Regenerates migrations/005_seed_official_pack.sql from seed/cards.json.
//
// The JSON file is the authoring format for the launch deck; the database is
// the runtime source of truth. Run this after editing seed/cards.json, but
// only before the migration has been applied anywhere — once applied, the
// migration runner rejects edits by checksum, and further content changes
// belong in a new migration (or, later, the admin desk).

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(repoRoot, 'migrations', '005_seed_official_pack.sql');
const deck = JSON.parse(readFileSync(join(repoRoot, 'seed', 'cards.json'), 'utf8'));

const PACK_SLUG = 'official-core';

function quote(value) {
  // standard_conforming_strings is on by default, so doubling the single
  // quote is the whole escape; backslashes are literal.
  return `'${String(value).replace(/'/g, "''")}'`;
}

function tuples(cards, kind) {
  const seen = new Set();
  return cards.map((card) => {
    const id = String(card.id || '').trim();
    const text = String(card.text || '').trim();
    const tier = String(card.tier || 'party').trim().toLowerCase();
    if (!id || !text) throw new Error(`${kind} card is missing id or text: ${JSON.stringify(card)}`);
    if (seen.has(id)) throw new Error(`duplicate ${kind} id ${id}`);
    if (tier !== 'family' && tier !== 'party') throw new Error(`${kind} ${id} has unsupported tier ${tier}`);
    seen.add(id);
    return `    (${quote(id)}, ${quote(text)}, ${quote(tier)})`;
  }).join(',\n');
}

const sql = `-- Generated by scripts/generate-card-seed-migration.mjs. Do not edit by hand.
-- Loads the launch deck into the content tables so the engine can read cards
-- from Postgres instead of seed/cards.json.

ALTER TABLE prompt_cards ADD COLUMN external_id TEXT UNIQUE;
ALTER TABLE answer_cards ADD COLUMN external_id TEXT UNIQUE;

COMMENT ON COLUMN prompt_cards.external_id IS
    'Stable id from the seed deck. NULL for cards created in the database.';
COMMENT ON COLUMN answer_cards.external_id IS
    'Stable id from the seed deck. NULL for cards created in the database.';

INSERT INTO packs (slug, title, description, source, tier, status)
VALUES (
    '${PACK_SLUG}',
    'Punchline Core',
    'The launch deck that ships with every room.',
    'official',
    'party',
    'approved'
)
ON CONFLICT (slug) DO NOTHING;

INSERT INTO prompt_cards (pack_id, external_id, text, tier, source, status)
SELECT p.id, v.external_id, v.text, v.tier::content_tier, 'official', 'approved'
FROM packs p
CROSS JOIN (VALUES
${tuples(deck.prompts, 'prompt')}
) AS v(external_id, text, tier)
WHERE p.slug = '${PACK_SLUG}'
ON CONFLICT (external_id) DO NOTHING;

INSERT INTO answer_cards (pack_id, external_id, text, tier, source, status)
SELECT p.id, v.external_id, v.text, v.tier::content_tier, 'official', 'approved'
FROM packs p
CROSS JOIN (VALUES
${tuples(deck.answers, 'answer')}
) AS v(external_id, text, tier)
WHERE p.slug = '${PACK_SLUG}'
ON CONFLICT (external_id) DO NOTHING;

CREATE INDEX idx_prompt_cards_tier_status ON prompt_cards(tier, status);
CREATE INDEX idx_answer_cards_tier_status ON answer_cards(tier, status);
`;

writeFileSync(target, sql);
console.log(JSON.stringify({
  generated: 'migrations/005_seed_official_pack.sql',
  prompts: deck.prompts.length,
  answers: deck.answers.length,
}));
